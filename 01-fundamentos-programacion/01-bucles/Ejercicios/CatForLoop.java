/*
    Ejercicio 1: Saludar gatitos (for)
    
    Objetivo: Repetir una acción varias veces usando un "for"
    
    Qué aprenderas:
    1. Cómo iniciar un for
    2. Contador simple
    3. Imprimir mensajes

    Enunciado:
    Imprime un saludo para 5 gatitos
*/



public class CatForLoop {
    public static void main(String[] args){
        for (int i = 1; i <= 5; i++){
            System.out.println("Hola gatito número: " + i);
        }
    }
}
